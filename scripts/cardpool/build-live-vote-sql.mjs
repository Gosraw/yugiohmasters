#!/usr/bin/env node
// scripts/cardpool/build-live-vote-sql.mjs
//
// Builds supabase/manual_deploy/20261012_live_vote_and_hotfix.sql:
// ONE file for the Supabase SQL Editor, ONE transaction, safe to
// run twice. It stitches together
//
//   a) supabase/manual_deploy/20261012_live_hotfix.sql (as is)
//   b) supabase/migrations/202610121900_card_votes_live.sql (the card
//      vote tables / RLS / RPCs)
//   c) the vote items seed, generated here from
//      data/cardpool/ranking-vote-lists.json (only vote_here items)
//   d) final self-checks
//
//   node scripts/cardpool/build-live-vote-sql.mjs
//
// It only writes a file - it never connects to any database.
//
// The seed resolves each card by card_catalog.external_card_id and
// the league as the one (non-archived) league that user 'bossg' is
// a member of - never a hardcoded league id. Cards missing from the
// catalog are skipped and listed in a NOTICE; fewer than
// MIN_RESOLVED resolved cards aborts the whole transaction.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "../..");

const HOTFIX = "supabase/manual_deploy/20261012_live_hotfix.sql";
const MIGRATION = "supabase/migrations/202610121900_card_votes_live.sql";
const VOTE_LISTS = "data/cardpool/ranking-vote-lists.json";
const OUTPUT = "supabase/manual_deploy/20261012_live_vote_and_hotfix.sql";

const OWNER_USERNAME = "bossg";
const MIN_RESOLVED = 380;
const EXPECTED_RESOLVED = 400;

function read(relative) {
  return readFileSync(path.join(ROOT, relative), "utf8");
}

// The parts keep their own content; only their own begin;/commit;
// lines go, because the whole file is one transaction.
function stripTransaction(sql, name) {
  const lines = sql.split("\n");
  const begins = lines.filter((line) => line.trim() === "begin;").length;
  const commits = lines.filter((line) => line.trim() === "commit;").length;

  if (begins !== 1 || commits !== 1) {
    throw new Error(`${name}: expected exactly one "begin;" and one "commit;" line, found ${begins} / ${commits}`);
  }

  return lines
    .filter((line) => line.trim() !== "begin;" && line.trim() !== "commit;")
    .join("\n")
    .trim();
}

function literal(value) {
  if (value === null || value === undefined) {
    return "null";
  }

  if (typeof value === "number") {
    if (!Number.isInteger(value)) {
      throw new Error(`Unexpected non-integer ${value}`);
    }

    return String(value);
  }

  const text = String(value);

  if (text.includes("\0")) {
    throw new Error("NUL byte in a seed value");
  }

  return `'${text.replaceAll("'", "''")}'`;
}

// "… (category: x; confidence: high)" is ranking-pipeline metadata,
// not something the players need to read on the vote card.
function cleanContext(text) {
  return String(text ?? "")
    .replace(/\s*\(category:[^)]*\)\s*$/, "")
    .replace(/\s*\(confidence:[^)]*\)\s*$/, "")
    .trim();
}

const voteLists = JSON.parse(read(VOTE_LISTS));

const rows = [];

voteLists.lists.forEach((list, listIndex) => {
  for (const item of list.items) {
    if (!item.vote_here) continue;

    rows.push([
      item.id,
      list.key,
      list.title,
      listIndex + 1,
      item.sort_order,
      item.proposed_verdict,
      cleanContext(item.context),
      item.name,
    ]);
  }
});

const ids = new Set(rows.map((row) => row[0]));

if (ids.size !== rows.length) {
  throw new Error("A card appears in more than one vote list - card_vote_items allows one item per card per league.");
}

const seedValues = rows
  .map((row) => `  (${row.map(literal).join(", ")})`)
  .join(",\n");

const hotfix = stripTransaction(read(HOTFIX), HOTFIX);
const migration = stripTransaction(read(MIGRATION), MIGRATION);

const output = `-- =========================================================
-- Duelist Circle - LIVE: card vote + hotfix (2026-10-12)
--
-- GENERATED by scripts/cardpool/build-live-vote-sql.mjs - edit the
-- sources and re-run it, not this file.
--
-- For the CURRENT live app (main). Paste the whole file into the
-- Supabase SQL Editor and run it once. Everything runs in ONE
-- transaction: if any check fails, nothing changes. Safe to run
-- twice (the second run changes nothing and keeps every vote).
--
--   PART A  ${HOTFIX}
--           (round rewards crash + unlimited welcome packs)
--   PART B  ${MIGRATION}
--           (card vote tables, RLS and functions - new objects only)
--   PART C  the ${rows.length} cards to vote on, from
--           ${VOTE_LISTS}
--   PART D  final checks
--
-- What to look for in the output: the NOTICE lines. "Card vote:
-- N of ${rows.length} cards ready" says how many cards the vote has.
-- =========================================================

begin;

-- =========================================================
-- PART A - live hotfix (${HOTFIX}, unchanged)
-- =========================================================

${hotfix}

-- =========================================================
-- PART B - card vote schema (${MIGRATION})
-- =========================================================

do $preflight$
begin
  if to_regclass('public.card_vote_items') is not null then
    raise notice 'Card vote: tables already exist - upgrading them in place (votes are kept).';
  else
    raise notice 'Card vote: creating the tables.';
  end if;
end;
$preflight$;

${migration}

-- =========================================================
-- PART C - vote items seed
--
-- external_card_id, list_key, list_title, list_order, sort_order,
-- proposed_verdict, context, card name (name only for messages).
-- =========================================================

-- A regular helper table (not TEMP): the Supabase SQL Editor can run
-- statements on different connections, where a temp table vanishes.
-- It is dropped again at the end of this file and is never readable
-- by the app (no grants, RLS on).
drop table if exists public.live_card_vote_seed;

create table public.live_card_vote_seed (
  external_card_id bigint primary key,
  list_key text not null,
  list_title text not null,
  list_order integer not null,
  sort_order integer not null,
  proposed_verdict text not null,
  context text not null,
  card_name text not null
);

alter table public.live_card_vote_seed enable row level security;

revoke all on public.live_card_vote_seed from public, anon, authenticated;

insert into live_card_vote_seed (
  external_card_id,
  list_key,
  list_title,
  list_order,
  sort_order,
  proposed_verdict,
  context,
  card_name
)
values
${seedValues};

do $seed$
declare
  owner_leagues integer;
  target_league uuid;
  seed_total integer;
  resolved integer;
  unresolved text;
  upserted integer;
begin
  select count(distinct lm.league_id)
  into owner_leagues
  from public.league_members lm
  join public.profiles p
    on p.id = lm.profile_id
  join public.leagues l
    on l.id = lm.league_id
  where p.username = ${literal(OWNER_USERNAME)}
    and l.archived_at is null;

  if owner_leagues <> 1 then
    raise exception 'CARD VOTE ABORTED: expected exactly one active league with member "${OWNER_USERNAME}", found %. Nothing changed - send this message to Claude.', owner_leagues;
  end if;

  select lm.league_id
  into target_league
  from public.league_members lm
  join public.profiles p
    on p.id = lm.profile_id
  join public.leagues l
    on l.id = lm.league_id
  where p.username = ${literal(OWNER_USERNAME)}
    and l.archived_at is null;

  select count(*)
  into seed_total
  from live_card_vote_seed;

  select count(*)
  into resolved
  from live_card_vote_seed s
  join public.card_catalog c
    on c.external_card_id = s.external_card_id;

  select string_agg(
    s.card_name || ' (' || s.external_card_id || ')',
    ', '
    order by s.list_order, s.sort_order
  )
  into unresolved
  from live_card_vote_seed s
  where not exists (
    select 1
    from public.card_catalog c
    where c.external_card_id = s.external_card_id
  );

  if resolved < ${MIN_RESOLVED} then
    raise exception 'CARD VOTE ABORTED: only % of % vote cards are in card_catalog (need at least ${MIN_RESOLVED}). Missing: %. Nothing changed - send this message to Claude.', resolved, seed_total, unresolved;
  end if;

  if unresolved is not null then
    raise notice 'Card vote: % card(s) are not in card_catalog and are skipped: %', seed_total - resolved, unresolved;
  end if;

  if resolved < ${EXPECTED_RESOLVED} then
    raise notice 'Card vote: only % of % cards resolved (fewer than ${EXPECTED_RESOLVED}) - check the skipped list above.', resolved, seed_total;
  end if;

  insert into public.card_vote_items (
    league_id,
    list_key,
    list_title,
    list_order,
    card_catalog_id,
    proposed_verdict,
    context,
    sort_order
  )
  select
    target_league,
    s.list_key,
    s.list_title,
    s.list_order,
    c.id,
    s.proposed_verdict,
    s.context,
    s.sort_order
  from live_card_vote_seed s
  join public.card_catalog c
    on c.external_card_id = s.external_card_id
  on conflict (league_id, card_catalog_id)
  do update set
    list_key = excluded.list_key,
    list_title = excluded.list_title,
    list_order = excluded.list_order,
    proposed_verdict = excluded.proposed_verdict,
    context = excluded.context,
    sort_order = excluded.sort_order
  where (
    card_vote_items.list_key,
    card_vote_items.list_title,
    card_vote_items.list_order,
    card_vote_items.proposed_verdict,
    card_vote_items.context,
    card_vote_items.sort_order
  ) is distinct from (
    excluded.list_key,
    excluded.list_title,
    excluded.list_order,
    excluded.proposed_verdict,
    excluded.context,
    excluded.sort_order
  );

  get diagnostics upserted = row_count;

  raise notice 'Card vote: % of % cards ready (% new or changed).', resolved, seed_total, upserted;

  -- For PART D.
  perform set_config('duelist.vote_league', target_league::text, true);
  perform set_config('duelist.vote_resolved', resolved::text, true);
end;
$seed$;

-- =========================================================
-- PART D - final checks (any failure undoes everything above)
-- =========================================================

do $verify$
declare
  target_league uuid := current_setting('duelist.vote_league')::uuid;
  resolved integer := current_setting('duelist.vote_resolved')::integer;
  seeded_items integer;
  missing_items integer;
  owner_id uuid;
begin
  select count(*)
  into seeded_items
  from public.card_vote_items i
  join public.card_catalog c
    on c.id = i.card_catalog_id
  join live_card_vote_seed s
    on s.external_card_id = c.external_card_id
  where i.league_id = target_league;

  if seeded_items <> resolved then
    raise exception 'CARD VOTE ABORTED: expected % vote items in the league, found %.', resolved, seeded_items;
  end if;

  select count(*)
  into missing_items
  from live_card_vote_seed s
  join public.card_catalog c
    on c.external_card_id = s.external_card_id
  where not exists (
    select 1
    from public.card_vote_items i
    where i.league_id = target_league
      and i.card_catalog_id = c.id
      and i.list_key = s.list_key
      and i.proposed_verdict = s.proposed_verdict
  );

  if missing_items <> 0 then
    raise exception 'CARD VOTE ABORTED: % vote items do not match the seed.', missing_items;
  end if;

  if exists (
    select 1
    from pg_class
    where oid in (
      'public.card_vote_items'::regclass,
      'public.card_votes'::regclass,
      'public.card_vote_tiebreaks'::regclass
    )
      and not relrowsecurity
  ) then
    raise exception 'CARD VOTE ABORTED: row level security is off on a card vote table.';
  end if;

  if to_regprocedure('public.cast_card_vote(uuid,text,text)') is null
     or to_regprocedure('public.set_vote_tiebreak(uuid,text,text)') is null
     or to_regprocedure('public.get_vote_results(uuid)') is null
     or to_regprocedure('public.card_vote_resolve(text,text)') is null
     or to_regprocedure('public.card_votes_before_write()') is null then
    raise exception 'CARD VOTE ABORTED: a card vote function is missing.';
  end if;

  if to_regprocedure('public.cast_card_vote(uuid,text)') is not null
     or to_regprocedure('public.set_vote_tiebreak(uuid,text)') is not null then
    raise exception 'CARD VOTE ABORTED: an old 2-argument vote function is still there.';
  end if;

  if not exists (
    select 1
    from pg_trigger
    where tgrelid = 'public.card_votes'::regclass
      and tgname = 'card_votes_before_write_trigger'
      and not tgisinternal
  ) then
    raise exception 'CARD VOTE ABORTED: the vote validation trigger is missing.';
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.card_votes'::regclass
      and conname = 'card_votes_allow_rarity_check'
  ) or not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.card_vote_tiebreaks'::regclass
      and conname = 'card_vote_tiebreaks_allow_rarity_check'
  ) then
    raise exception 'CARD VOTE ABORTED: the allow_rarity checks are missing.';
  end if;

  if has_table_privilege('anon', 'public.card_votes', 'select')
     or has_table_privilege('anon', 'public.card_vote_items', 'select')
     or has_table_privilege('authenticated', 'public.card_votes', 'delete')
     or has_table_privilege('authenticated', 'public.card_vote_items', 'insert')
     or has_table_privilege('authenticated', 'public.card_vote_tiebreaks', 'insert')
     or has_function_privilege('anon', 'public.cast_card_vote(uuid,text,text)', 'execute')
     or has_function_privilege('anon', 'public.get_vote_results(uuid)', 'execute') then
    raise exception 'CARD VOTE ABORTED: table or function rights are wider than intended.';
  end if;

  -- Read the results the way the app does: as the owner, through
  -- RLS (role authenticated). Local to this transaction.
  select p.id
  into owner_id
  from public.profiles p
  where p.username = ${literal(OWNER_USERNAME)};

  perform set_config('request.jwt.claim.sub', owner_id::text, true);
  perform set_config(
    'request.jwt.claims',
    json_build_object('sub', owner_id, 'role', 'authenticated')::text,
    true
  );
end;
$verify$;

set local role authenticated;

do $verify_as_owner$
declare
  target_league uuid := current_setting('duelist.vote_league')::uuid;
  visible_items integer;
  result_rows integer;
begin
  select count(*)
  into visible_items
  from public.card_vote_items
  where league_id = target_league;

  select count(*)
  into result_rows
  from public.get_vote_results(target_league);

  if visible_items = 0 or result_rows <> visible_items then
    raise exception 'CARD VOTE ABORTED: the owner sees % items and % results.', visible_items, result_rows;
  end if;

  raise notice 'Card vote: the owner sees % cards on /vote. All checks passed.', visible_items;
end;
$verify_as_owner$;

reset role;

select set_config('request.jwt.claim.sub', '', true);
select set_config('request.jwt.claims', '', true);

-- Let the API (PostgREST) see the new functions straight away;
-- delivered at commit.
drop table if exists public.live_card_vote_seed;

notify pgrst, 'reload schema';

commit;
`;

writeFileSync(path.join(ROOT, OUTPUT), output);

console.log(`Wrote ${OUTPUT}: ${rows.length} vote items in ${voteLists.lists.length} lists.`);
