#!/usr/bin/env node
// Builds supabase/manual_deploy/20261102_pack_rebalance.sql: the text of
// supabase/migrations/202611021000_pack_rebalance.sql, unchanged, plus a
// verification SELECT, for pasting into the Supabase SQL Editor.
//
//   node scripts/season2/build-pack-rebalance-manual.mjs          # write
//   node scripts/season2/build-pack-rebalance-manual.mjs --check  # compare
//
// The migration is the only copy to edit.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "../..");
const MIGRATION = path.join(ROOT, "supabase/migrations/202611021000_pack_rebalance.sql");
const OUTPUT = path.join(ROOT, "supabase/manual_deploy/20261102_pack_rebalance.sql");

const HEADER = `-- =========================================================
-- PASTE THIS WHOLE FILE INTO THE SUPABASE SQL EDITOR, THEN PRESS RUN.
--
-- Pack rebalance. It is one transaction: if anything goes wrong, nothing
-- changes. Pressing Run a second time does no harm.
--
-- The result is one row. checks_passed must say true.
--
-- Generated by scripts/season2/build-pack-rebalance-manual.mjs from
-- supabase/migrations/202611021000_pack_rebalance.sql. Don't edit here.
-- =========================================================

`;

const VERIFICATION = `

-- =========================================================
-- VERIFICATION (reads only)
-- =========================================================

select
  (select price_dp from public.shop_pack_types where code = 'normal') as standard_price,
  (select cards_per_pack from public.shop_pack_types where code = 'normal') as standard_cards,
  (select price_dp from public.shop_pack_types where code = 'premium') as premium_price,
  (select cards_per_pack from public.shop_pack_types where code = 'premium') as premium_cards,
  (select price_dp from public.shop_pack_types where code = 'deluxe') as deluxe_price,
  (select cards_per_pack from public.shop_pack_types where code = 'deluxe') as deluxe_cards,
  (
    select string_agg(theme_category || ': ' || price_dp || ' DP, ' || cards_per_pack || ' cards', ' | ' order by theme_category)
    from public.shop_special_pack_rotations
    where status = 'active'
  ) as active_special_rotations,
  (
    (select count(*) from public.shop_pack_types where (code, price_dp, cards_per_pack) in (('normal', 400, 5), ('premium', 900, 10), ('deluxe', 1500, 14))) = 3
    and exists (select 1 from public.shop_special_pack_rotations where status = 'active')
    and not exists (select 1 from public.shop_special_pack_rotations where status = 'active' and (price_dp, cards_per_pack) is distinct from (1000, 10))
    and pg_get_functiondef('public.refresh_shop_special_pack_rotation_if_needed(text)'::regprocedure) like '%1000,%'
    and pg_get_functiondef('public.purchase_shop_pack(text, uuid)'::regprocedure) like '%_pick_shop_pack_card_constrained%'
    and pg_get_functiondef('public.roll_shop_pack_peak_rarity(text)'::regprocedure) like '%legendary_pct := 8;%'
    and pg_get_functiondef('public.roll_shop_pack_filler_rarity(text)'::regprocedure) like '%normal_pct := 75;%'
    and to_regprocedure('public._pick_shop_pack_card_constrained(uuid, text, uuid, text[], uuid[])') is not null
  ) as checks_passed;
`;

const expected = HEADER + readFileSync(MIGRATION, "utf8").trimEnd() + "\n" + VERIFICATION;

if (process.argv.includes("--check")) {
  if (readFileSync(OUTPUT, "utf8") !== expected) {
    console.error(`${path.relative(ROOT, OUTPUT)} is out of date. Run this script to rebuild it.`);
    process.exit(1);
  }

  console.log("manual deploy file matches the migration");
} else {
  writeFileSync(OUTPUT, expected);
  console.log(`wrote ${path.relative(ROOT, OUTPUT)} (${expected.length} bytes)`);
}
