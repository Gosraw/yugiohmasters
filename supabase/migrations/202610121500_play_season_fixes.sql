-- =========================================================
-- Play / season bug-hunt fixes (2026-10-12).
--
-- Backwards compatible with the live `main` app: only adds a
-- column, a flag, a status value and guards; no signature changes.
--
-- 1. duel_point_transactions.seq: a stable ledger order. Rows
--    written in one transaction share created_at, so "newest first"
--    had no tie-breaker and the wallet's running balance looked
--    wrong after a correction. New rows get the identity value in
--    insert order; existing rows are back-filled per player in
--    created_at order, with ties ordered so each row's
--    (balance_after - amount) continues the previous row's balance.
-- 2. competitions.is_season: an explicit "this is THE season"
--    flag. Before, every V2 round robin (meetings_per_pairing set)
--    counted as the season for bounty / catch-up / Season Path XP /
--    weekly goals. At most one draft/active season per league.
--    mark_competition_as_season() sets it (admin only).
-- 3. submit_competition_match_result_v2: the status guards (no
--    result for a cancelled/declined duel or a competition that is
--    not active) now apply to league admins too.
-- 4. settle_match_wagers: the losing player's DP escrow is marked
--    'lost' (was 'won' for both players).
-- =========================================================

-- ---------------------------------------------------------
-- 1. Ledger order
-- ---------------------------------------------------------

alter table public.duel_point_transactions
  add column if not exists seq bigint;

do $$
declare
  prof uuid;
  grp timestamptz;
  running integer;
  pick_id uuid;
  pick_balance integer;
  counter bigint := 0;
begin
  if not exists (
    select 1 from public.duel_point_transactions where seq is null
  ) then
    return;
  end if;

  create temp table _dpt_order (
    id uuid primary key,
    ord bigint not null
  ) on commit drop;

  for prof in
    select distinct profile_id from public.duel_point_transactions
  loop
    running := null;

    for grp in
      select distinct created_at
      from public.duel_point_transactions
      where profile_id = prof
      order by created_at
    loop
      loop
        pick_id := null;

        select d.id, d.balance_after
        into pick_id, pick_balance
        from public.duel_point_transactions d
        where d.profile_id = prof
          and d.created_at = grp
          and not exists (select 1 from _dpt_order o where o.id = d.id)
        order by
          (running is not null and d.balance_after - d.amount = running) desc,
          d.id
        limit 1;

        exit when pick_id is null;

        counter := counter + 1;
        insert into _dpt_order (id, ord) values (pick_id, counter);
        running := pick_balance;
      end loop;
    end loop;
  end loop;

  update public.duel_point_transactions d
  set seq = ranked.rn
  from (
    select o.id, row_number() over (order by t.created_at, o.ord) as rn
    from _dpt_order o
    join public.duel_point_transactions t on t.id = o.id
  ) ranked
  where ranked.id = d.id;
end;
$$;

alter table public.duel_point_transactions
  alter column seq set not null;

do $$
begin
  if not exists (
    select 1
    from pg_attribute
    where attrelid = 'public.duel_point_transactions'::regclass
      and attname = 'seq'
      and attidentity <> ''
  ) then
    alter table public.duel_point_transactions
      alter column seq add generated by default as identity;
  end if;

  perform setval(
    pg_get_serial_sequence('public.duel_point_transactions', 'seq'),
    greatest(coalesce((select max(seq) from public.duel_point_transactions), 0), 1),
    (select count(*) > 0 from public.duel_point_transactions)
  );
end;
$$;

create unique index if not exists duel_point_transactions_seq_key
  on public.duel_point_transactions (seq);

create index if not exists duel_point_transactions_profile_seq_idx
  on public.duel_point_transactions (profile_id, seq desc);

comment on column public.duel_point_transactions.seq is
  'Stable ledger order (insert order). Rows of one transaction share created_at; order by created_at, seq.';

