-- 2. Explicit season flag
-- ---------------------------------------------------------

alter table public.competitions
  add column if not exists is_season boolean not null default false;

-- Existing data: a V2 round robin that is called a season or has a
-- season-length schedule (custom events are 1-3 meetings).
update public.competitions
set is_season = true
where is_season = false
  and competition_type = 'round_robin'
  and meetings_per_pairing is not null
  and (name ilike '%season%' or meetings_per_pairing >= 10);

-- Keep one draft/active season per league: the one Play already
-- opened (longest schedule, newest first).
with ranked as (
  select
    id,
    row_number() over (
      partition by league_id
      order by total_rounds desc nulls last, created_at desc
    ) as rn
  from public.competitions
  where is_season
    and status in ('draft', 'active')
)
update public.competitions c
set is_season = false
from ranked
where ranked.id = c.id
  and ranked.rn > 1;

create unique index if not exists competitions_one_open_season_per_league
  on public.competitions (league_id)
  where is_season and status in ('draft', 'active');

create or replace function public._is_season_competition(target_competition_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.competitions c
    where c.id = target_competition_id
      and c.is_season
  );
$$;

revoke all on function public._is_season_competition(uuid) from public, anon, authenticated;

-- Admin-only: flag a freshly created competition as the league's
-- season. Refuses while another season is still draft/active.
create or replace function public.mark_competition_as_season(target_competition_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  competition_row public.competitions%rowtype;
begin
  if current_user_id is null then
    raise exception 'Not authenticated.';
  end if;

  select * into competition_row
  from public.competitions
  where id = target_competition_id
  for update;

  if not found then
    raise exception 'Competition not found.';
  end if;

  if not exists (
    select 1
    from public.league_members
    where league_id = competition_row.league_id
      and profile_id = current_user_id
      and role = 'admin'
  ) then
    raise exception 'Only a league admin can start a season.';
  end if;

  if competition_row.competition_type <> 'round_robin'
     or competition_row.meetings_per_pairing is null then
    raise exception 'Only a V2 round robin can be the season.';
  end if;

  if exists (
    select 1
    from public.competitions c
    where c.league_id = competition_row.league_id
      and c.id <> competition_row.id
      and c.is_season
      and c.status in ('draft', 'active')
  ) then
    raise exception 'A season is already running. Finish it before starting a new one.';
  end if;

  update public.competitions
  set is_season = true,
      updated_at = now()
  where id = competition_row.id;
end;
$$;

revoke all on function public.mark_competition_as_season(uuid) from public, anon;
grant execute on function public.mark_competition_as_season(uuid) to authenticated;

-- Season Path XP and weekly goals: only SEASON duels count (they
-- counted any competition duel). Bodies are otherwise unchanged:
-- the live definition is re-created with just that filter swapped.
do $$
declare
  target regprocedure;
  def text;
  patched text;
begin
  foreach target in array array[
    'public._weekly_goal_progress_count(text,jsonb,uuid,uuid,timestamptz,timestamptz)'::regprocedure,
    'public._sync_season_path_xp(uuid,integer)'::regprocedure
  ]
  loop
    def := pg_get_functiondef(target);
    patched := replace(
      def,
      'm.competition_id is not null',
      'public._is_season_competition(m.competition_id)'
    );

    if patched <> def then
      execute patched;
    end if;
  end loop;
end;
$$;

-- ---------------------------------------------------------
-- 3. submit_competition_match_result_v2: guards for everyone.
-- Body copied from 202610121220_competition_submit_guards.sql; only
-- the guard block changed (no longer skipped for admins).
-- ---------------------------------------------------------

create or replace function public.submit_competition_match_result_v2(
  target_match_id uuid,
  target_player_one_duel_wins integer,
  target_player_two_duel_wins integer
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid;
  match_row public.matches%rowtype;
  competition_row public.competitions%rowtype;
  is_admin boolean;
  computed_winner uuid;
  computed_result public.match_result_type;
begin
  current_user_id := auth.uid();

  if current_user_id is null then
    raise exception 'Not authenticated.';
  end if;

  select * into match_row from public.matches where id = target_match_id for update;

  if not found then
    raise exception 'Match not found.';
  end if;

  if match_row.competition_id is null then
    raise exception 'This match is not part of a competition.';
  end if;

  select * into competition_row from public.competitions where id = match_row.competition_id;

  select (role = 'admin')
  into is_admin
  from public.league_members
  where league_id = competition_row.league_id
    and profile_id = current_user_id;

  if is_admin is not true
     and current_user_id not in (match_row.player_one_id, match_row.player_two_id) then
    raise exception 'Only a player in this duel or a league admin can submit its result.';
  end if;

  if competition_row.status is distinct from 'active' then
    raise exception 'This competition is not active.';
  end if;

  if match_row.status in ('cancelled', 'declined') then
    raise exception 'This match can no longer take a result.';
  end if;

  if match_row.status = 'completed' then
    raise exception 'This match already has a result - use correct_competition_match_result_v2 to change it.';
  end if;

  if match_row.match_format = 'single_duel' then
    if not (
      (target_player_one_duel_wins = 1 and target_player_two_duel_wins = 0)
      or (target_player_one_duel_wins = 0 and target_player_two_duel_wins = 1)
    ) then
      raise exception 'Single Duel requires exactly one winner (1-0 or 0-1).';
    end if;
  else
    if not (
      (target_player_one_duel_wins = 2 and target_player_two_duel_wins in (0, 1))
      or (target_player_two_duel_wins = 2 and target_player_one_duel_wins in (0, 1))
    ) then
      raise exception 'Best of 3 requires a first-to-2 score (2-0 or 2-1).';
    end if;
  end if;

  if target_player_one_duel_wins > target_player_two_duel_wins then
    computed_winner := match_row.player_one_id;
    computed_result := 'player_one_win';
  else
    computed_winner := match_row.player_two_id;
    computed_result := 'player_two_win';
  end if;

  update public.matches
  set
    player_one_duel_wins = target_player_one_duel_wins,
    player_two_duel_wins = target_player_two_duel_wins,
    winner_id = computed_winner,
    result = computed_result,
    status = 'completed',
    result_submitted_by = current_user_id,
    result_submitted_at = now(),
    completed_at = now(),
    updated_at = now()
  where id = target_match_id;

  perform public._award_match_duel_points_internal(target_match_id);

  perform public.refresh_competition_current_round_v2(match_row.competition_id);

  perform public.settle_round_rewards_v2(match_row.competition_id, match_row.round_number);
  perform public.settle_competition_if_complete_v2(match_row.competition_id);
end;
$$;

revoke all on function public.submit_competition_match_result_v2(uuid, integer, integer) from public, anon;
grant execute on function public.submit_competition_match_result_v2(uuid, integer, integer) to authenticated;

-- ---------------------------------------------------------
-- 4. Wager escrow: the loser's stake is 'lost', not 'won'.
-- ---------------------------------------------------------

alter table public.match_dp_escrows
  drop constraint if exists match_dp_escrows_status_check;

alter table public.match_dp_escrows
  add constraint match_dp_escrows_status_check
  check (status in ('funded', 'won', 'lost', 'refunded'));

do $$
declare
  def text;
  patched text;
begin
  def := pg_get_functiondef('public.settle_match_wagers(uuid)'::regprocedure);
  patched := regexp_replace(
    def,
    'then\s+''won''\s+else\s+''won''',
    'then ''won''
          else ''lost'''
  );

  if patched = def and position('''lost''' in def) = 0 then
    raise exception 'settle_match_wagers: expected escrow status case not found';
  end if;

  if patched <> def then
    execute patched;
  end if;
end;
$$;

-- Existing settled wagers: the loser's escrow row.
update public.match_dp_escrows e
set status = 'lost'
from public.matches m
where m.id = e.match_id
  and e.status = 'won'
  and m.winner_id is not null
  and e.profile_id <> m.winner_id;
